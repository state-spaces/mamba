// 与 op_kernel InitBuffers 的缓冲清单逐项对应（v3，单缓冲），用于反推 chunkRows。
// 6 组 dtype 元素宽度：state / BC / X / Proj，另加 fp32 工作平面。
int64_t UbBytesForChunk(int64_t rows, int64_t dState, int64_t rank, int64_t rankBlock, int64_t eszState,
                        int64_t eszBC, int64_t eszX, int64_t eszProj)
{
    int64_t total = 0;
    total += Align32(rows * dState * eszState);          // raw (state)
    total += Align32(rows * dState * eszState);          // wb (state_out stage)
    total += Align32(rows * rank * eszX);                // outRaw (no-outproj: rank 行一次写回)
    total += Align32(rows * rank * 4);                   // outF (no-outproj 的 rank 行 fp32)
    total += 3 * Align32(rankBlock * dState * eszBC);    // bcStage
    total += 3 * Align32(rankBlock * rows * eszProj);    // projStage
    total += 3 * Align32(rows * eszX);                   // vecStage
    total += 128;                                         // scalarStage
    total += Align32(rows * dState * 4);                 // sF
    total += Align32(rows * dState * 4);                 // prod / w64
    total += 3 * Align32(rankBlock * dState * 4);        // bcF
    total += 3 * Align32(rankBlock * rows * 4);          // projF
    total += 10 * Align32(rows * 4);                      // x/xs/z/u/v/dx/w/tmp/gate/acc
    total += 2 * Align32(rows * MAMBA3_SLOT * 4);        // dot / w8
    total += 256 + 64;                                    // scalar / expTmp
    return total;
}

int64_t ChooseChunkRows(int64_t tileD, int64_t dState, int64_t rank, int64_t rankBlock, int64_t eszState,
                        int64_t eszBC, int64_t eszX, int64_t eszProj)
{
    // 每行必须是 8 的倍数：Brcb 以 8 个元素为一组做 32B 广播
    const int64_t divisors[5] = {128, 64, 32, 16, 8};
    for (int i = 0; i < 5; ++i) {
        const int64_t cand = divisors[i];
        if (tileD % cand != 0) {
            continue;
        }
        if (UbBytesForChunk(cand, dState, rank, rankBlock, eszState, eszBC, eszX, eszProj) <= kUbChunkBudget) {
            return cand;
        }
    }
    return 8;
}

